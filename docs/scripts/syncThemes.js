// Regenerates `docs/src/lib/themes.js` from the preset's canonical
// `themeOrder` export and verifies it against `src/theme/themes.css`.
// Run: `bun run sync:themes` (from docs/) or `bun docs/scripts/syncThemes.js`
// (from repo root). Upstream `(routes)/+layout.server.js` imported
// `daisyui/functions/themeOrder` from the workspace package; this script is
// the offline equivalent — docs resolves the 35-theme list with no `daisyui`
// dependency at runtime.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..");
const orderPath = join(repoRoot, "src", "theme", "order.ts");
const cssPath = join(repoRoot, "src", "theme", "themes.css");
const outPath = join(here, "..", "src", "lib", "themes.js");

function parseOrderTs(text) {
  const match = text.match(
    /export const themeOrder: string\[\] = \[([\s\S]*?)\];/,
  );
  if (!match) throw new Error(`themeOrder array not found in ${orderPath}`);
  return [...match[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
}

function parseCssBanners(text) {
  return [...text.matchAll(/\/\* --- ([a-z0-9]+) /g)].map((m) => m[1]);
}

const order = parseOrderTs(readFileSync(orderPath, "utf8"));
const banners = parseCssBanners(readFileSync(cssPath, "utf8"));

if (order.length !== 35)
  throw new Error(`expected 35 themes, got ${order.length}`);
if (JSON.stringify(order) !== JSON.stringify(banners)) {
  throw new Error(
    `preset themeOrder diverged from themes.css banners.\norder.ts: ${order.join(",")}\nbanners:  ${banners.join(",")}`,
  );
}

const header = `// GENERATED by \`bun run sync:themes\` (docs/scripts/syncThemes.js) from the
// preset's \`themeOrder\` export (src/theme/order.ts — hard fork of
// packages/daisyui/functions/themeOrder.js). Do not hand-edit; run the
// sync script instead. \`tests/docs-chrome.test.ts\` fails when this copy
// drifts from the preset or from src/theme/themes.css banner order.
//
// Replaces upstream \`(routes)/+layout.server.js\`:
//   import themes from "daisyui/functions/themeOrder"
// which coupled docs to the \`daisyui\` workspace package. This module lets
// docs resolve the 35-theme list (ThemeChange switcher, theme matrix pages)
// with no \`daisyui\` dependency at runtime.
`;

writeFileSync(
  outPath,
  `${header}export const themeOrder = [\n${order.map((t) => `  "${t}",`).join("\n")}\n];\n`,
);
console.log(`[sync:themes] wrote ${outPath} (${order.length} themes, in sync)`);
